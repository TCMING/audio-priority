import Foundation
let directory = FileManager.default.temporaryDirectory.appendingPathComponent(UUID().uuidString)
try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
defer { try? FileManager.default.removeItem(at: directory) }
let store = SettingsStore(directory: directory)
let a = OutputDevice(id: 1, uid: "uid-a", name: "Headphones")
let b = OutputDevice(id: 2, uid: "uid-b", name: "Display")
let c = OutputDevice(id: 3, uid: "uid-c", name: "Speakers")
try JSONEncoder().encode(["Headphones", "Display", "Speakers"]).write(to: directory.appendingPathComponent("priorities.json"))
let migrated = try store.update(connected: [c, a, b])
assert(migrated.devices.map(\.uid) == ["uid-a", "uid-b", "uid-c"])
let reordered = try store.update(connected: [a, b, c], orderedUIDs: ["uid-b", "uid-a", "uid-c"])
assert(reordered.devices.map(\.uid) == ["uid-b", "uid-a", "uid-c"])
assert(bestOutput([a, b, c], settings: reordered)?.uid == "uid-b")
assert(bestOutput([a, c], settings: reordered)?.uid == "uid-a")
assert(bestOutput([c], settings: reordered)?.uid == "uid-c")
let offline = try store.update(connected: [c])
assert(offline == reordered)
let d = OutputDevice(id: 4, uid: "uid-d", name: "Headphones")
let discovered = try store.update(connected: [c, d])
assert(discovered.devices.map(\.uid) == ["uid-b", "uid-a", "uid-c", "uid-d"])
let repeated = try store.update(connected: [c, d]); assert(repeated == discovered)
let saved = try JSONDecoder().decode(Settings.self, from: Data(contentsOf: directory.appendingPathComponent("priorities.json")))
assert(saved == discovered)
print("PASS migration, reorder, persistence, disconnect fallback, discovery, duplicate names")
